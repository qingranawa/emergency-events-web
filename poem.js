// 名言管理系统
class QuoteManager {
    constructor() {
        this.quotes = [...quotes];
        this.displayedQuotes = [];
        this.totalQuotes = quotes.length;
        this.currentIndex = 0;
    }

    getRandomQuote() {
        // 如果所有名言都已显示过，重置记录
        if (this.displayedQuotes.length >= this.totalQuotes) {
            this.displayedQuotes = [];
        }

        // 过滤出未显示的名言
        const availableQuotes = this.quotes.filter(
            quote => !this.displayedQuotes.includes(quote)
        );

        // 随机选择一条
        const randomIndex = Math.floor(Math.random() * availableQuotes.length);
        const selectedQuote = availableQuotes[randomIndex];

        // 记录已显示的名言
        this.displayedQuotes.push(selectedQuote);
        this.currentIndex = this.displayedQuotes.length;

        return selectedQuote;
    }

    getNextQuote() {
        return this.getRandomQuote();
    }

    getProgress() {
        return {
            current: this.currentIndex,
            total: this.totalQuotes
        };
    }
}

// 初始化名言管理器
const quoteManager = new QuoteManager();

// 显示每日一言
function displayDailyQuote() {
    const quoteElement = document.getElementById('daily-quote');
    const countElement = document.getElementById('quote-count');

    if (quoteElement) {
        // 移除旧动画类
        quoteElement.classList.remove('animate-in');

        // 触发重绘
        void quoteElement.offsetWidth;

        // 获取新名言
        const newQuote = quoteManager.getNextQuote();
        quoteElement.textContent = newQuote;

        // 添加动画类
        quoteElement.classList.add('animate-in');

        // 更新计数器
        if (countElement) {
            const progress = quoteManager.getProgress();
            countElement.textContent = `${progress.current}/${progress.total}`;
        }
    }
}

// 页面加载完成后显示
document.addEventListener('DOMContentLoaded', () => {
    displayDailyQuote();

    // 添加刷新按钮事件
    const refreshBtn = document.getElementById('refresh-quote');
    if (refreshBtn) {
        refreshBtn.addEventListener('click', (e) => {
            e.preventDefault();
            displayDailyQuote();
        });
    }
});

// 点击名言区域也可以刷新
document.getElementById('daily-quote')?.addEventListener('click', displayDailyQuote);